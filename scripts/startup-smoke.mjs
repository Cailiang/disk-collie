import assert from 'node:assert/strict'
export async function startupLayout(page){
  const workspace=page.locator('.space-startup')
  await workspace.locator('.startup-group').first().waitFor()
  assert.equal(await workspace.getByRole('group',{name:'启动项状态',exact:true}).getByRole('button').count(),4)
  const code=workspace.locator('[data-startup-group="vscode"]')
  await code.locator('.startup-group-name').click();await code.locator('.startup-item').first().waitFor()
  assert.equal(await code.locator('.startup-item').count(),2,'One app retains every startup source')
  assert.match(await code.innerText(),/部分启用/)
  assert.match(await code.innerText(),/当前未运行/,'Not running must remain distinct from disabled')
  const box=await workspace.boundingBox()
  assert(box.x>=0&&box.x+box.width<=await page.evaluate(()=>innerWidth)+1)
  assert(await workspace.evaluate(element=>element.scrollWidth<=element.clientWidth+1),'Startup details must fit narrow windows')
  return workspace
}
export async function verifyStartup(browser,baseUrl,directory){
  const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  try{
    await page.goto(baseUrl);await page.locator('.nav-button[title="启动项优化"]').click()
    const workspace=await startupLayout(page),group=id=>workspace.locator(`[data-startup-group="${id}"]`),filters=workspace.getByRole('group',{name:'启动项状态',exact:true})
    assert.equal(await workspace.locator('.startup-group').count(),7)
    await workspace.getByRole('checkbox',{name:'显示系统项目',exact:true}).check()
    assert.equal(await workspace.locator('.startup-group').count(),8)
    assert(await group('system').getByRole('switch').isDisabled(),'System entries must remain protected')
    await workspace.getByRole('checkbox',{name:'显示系统项目',exact:true}).uncheck()
    await filters.getByRole('button',{name:/已禁用/}).click()
    assert.equal(await workspace.locator('.startup-group').count(),2)
    await group('figma').locator('.startup-group-row').getByRole('switch',{name:'启用 Figma',exact:true}).click()
    const dialog=page.getByRole('dialog');assert.match(await dialog.innerText(),/不会卸载|不会.*结束/)
    await dialog.getByRole('button',{name:'启用',exact:true}).click();await dialog.waitFor({state:'hidden'})
    assert.equal(await group('figma').count(),0,'The disabled filter updates after verified enable')
    await filters.getByRole('button',{name:/全部/}).click()
    assert.equal(await group('figma').locator('.startup-group-row').getByRole('switch').getAttribute('aria-checked'),'true')
    await group('vscode').locator('.startup-group-row').getByRole('switch').click()
    assert.equal(await page.getByRole('dialog').locator('.space-dialog-files>div').count(),2)
    assert.match(await page.getByRole('dialog').innerText(),/其他触发条件/)
    await page.getByRole('dialog').getByRole('button',{name:'禁用',exact:true}).click();await page.getByRole('dialog').waitFor({state:'hidden'})
    assert.equal(await group('vscode').getByText('已禁用',{exact:true}).count(),3,'Group changes must update each source and the aggregate')
    await filters.getByRole('button',{name:/残留项/}).click();assert.equal(await workspace.locator('.startup-group').count(),2)
    assert(await group('embedded').getByRole('switch').isDisabled(),'Unknown/read-only leftovers cannot be toggled')
    const remove=()=>group('old-cloud').locator('.startup-group-row').getByRole('button',{name:'移除启动配置 Old Cloud',exact:true})
    await remove().click();assert.match(await page.getByRole('dialog').innerText(),/不删除程序、工作目录或个人文件/)
    await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click();assert.equal(await group('old-cloud').count(),1)
    await remove().click();await page.getByRole('dialog').getByRole('button',{name:'移除启动配置',exact:true}).click();await page.getByRole('dialog').waitFor({state:'hidden'})
    assert.equal(await group('old-cloud').count(),0);assert.equal(await group('embedded').count(),1)
    await filters.getByRole('button',{name:/全部/}).click();await workspace.getByRole('searchbox',{name:'搜索应用、发布者或启动路径',exact:true}).fill('Microsoft')
    assert.equal(await workspace.locator('.startup-group').count(),1)
    await page.locator('.nav-button[title="首页"]').click();await page.locator('.nav-button[title="启动项优化"]').click()
    assert.equal(await workspace.getByRole('searchbox').inputValue(),'Microsoft');assert.equal(await workspace.locator('.startup-group').count(),1)
    await group('vscode').locator('.startup-group-row').getByRole('button',{name:'询问 AI Visual Studio Code',exact:true}).click()
    await page.locator('.ai-task-row.phase-ready').first().waitFor();await page.getByRole('button',{name:'查看结果',exact:true}).click()
    assert.match(await page.locator('.message.user').last().innerText(),/启动项/)
    await page.getByRole('button',{name:'返回启动项优化',exact:true}).click()
    assert.equal(await workspace.getByRole('searchbox').inputValue(),'Microsoft')
    await workspace.getByRole('searchbox').fill('');await page.screenshot({path:`${directory}/startup-changes.png`})
    await workspace.getByRole('button',{name:'启动项操作记录',exact:true}).click();assert.match(await page.getByRole('dialog').innerText(),/Figma/);await page.getByRole('dialog').getByRole('button',{name:'关闭',exact:true}).click()
    assert.deepEqual(errors,[])
    console.log('Startup UI passed: grouped sources, state filters, protected/unknown items, verified toggle, registration-only removal, cancelled confirmation, AI and retained navigation')
  }finally{await page.close()}
}
