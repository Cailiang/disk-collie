import assert from 'node:assert/strict'
export async function verifySettingsAndStartupIgnore(page,directory,width){
  assert.equal(await page.locator('.sidebar .nav-button[title="设置"]').count(),1)
  assert.equal(await page.locator('.sidebar .utility-nav').count(),0)
  assert.equal((await page.locator('.settings-entry strong').textContent()).trim(),'设置')
  await page.locator('.nav-button[title="启动项优化"]').click()
  const workspace=page.locator('.space-startup'),group=workspace.locator('[data-startup-group="vscode"]')
  await group.waitFor()
  if(await group.locator('.startup-group-name').getAttribute('aria-expanded')!=='true')await group.locator('.startup-group-name').click()
  await group.locator('.startup-item .startup-ignore').first().click()
  assert.equal(await group.locator('.startup-item').count(),1)
  await workspace.getByRole('button',{name:'重新扫描',exact:true}).click()
  await workspace.locator('.startup-summary .spinner').waitFor({state:'hidden'})
  assert.equal(await group.locator('.startup-item').count(),1,'Ignored startup entries must stay hidden after rescanning')
  await workspace.getByRole('button',{name:'已忽略 1 项',exact:true}).click()
  const dialog=page.locator('.startup-ignored-dialog')
  assert.match(await dialog.innerText(),/不会禁用、移除或修改/)
  const box=await dialog.locator('.space-dialog').boundingBox();assert(box.x>=0&&box.x+box.width<=width+1)
  await page.screenshot({path:`${directory}/${width}-startup-ignored.png`})
  await dialog.getByRole('button',{name:'恢复显示',exact:true}).click();await dialog.getByRole('button',{name:'关闭',exact:true}).click()
  assert.equal(await group.locator('.startup-item').count(),2)
  await group.locator('.startup-group-row .startup-ignore').click();assert.equal(await group.count(),0)
  await workspace.getByRole('button',{name:'重新扫描',exact:true}).click();await workspace.locator('.startup-summary .spinner').waitFor({state:'hidden'})
  assert.equal(await group.count(),0)
  await workspace.getByRole('button',{name:'已忽略 2 项',exact:true}).click()
  await dialog.getByRole('button',{name:'恢复显示',exact:true}).first().click();await dialog.getByRole('button',{name:'恢复显示',exact:true}).first().click()
  await dialog.getByRole('button',{name:'关闭',exact:true}).click();assert.equal(await group.count(),1)
}
